use Illuminate\Support\Facades\Route;

Route::prefix('v1')->group(function (): void {
    Route::get('/cities', [CityController::class, 'index']);
    Route::get('/public/trips', [PublicTripController::class, 'index']);
    Route::get('/public/trips/{trip}', [PublicTripController::class, 'show']);
    Route::get('/public/trips/{trip}/expenses', [PublicTripController::class, 'expenses']);

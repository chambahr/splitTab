        Route::post('/invitations/accept', [InvitationController::class, 'accept'])->middleware('throttle:10,1');
        Route::post('/private-access/verify', [InvitationController::class, 'verifyOtp'])->middleware('throttle:5,1');
        Route::post('/trips/{trip}/private-access/request', [InvitationController::class, 'requestOtp'])->middleware('throttle:3,1');
        Route::post('/logout', [AuthController::class, 'logout']);
        Route::patch('/me', [PublicProfileController::class, 'update']);
        Route::get('/notifications', [NotificationController::class, 'index']);
        Route::post('/notifications/{notification}/read', [NotificationController::class, 'markRead']);
        Route::get('/coins', [CoinController::class, 'balance']);
        Route::get('/coins/history', [CoinController::class, 'history']);
        Route::post('/public/trips/{trip}/gift-coins', [CoinController::class, 'gift'])->middleware('throttle:10,1');
        Route::post('/trips/{trip}/reviews', [TripReviewController::class, 'store'])->middleware('throttle:10,1');
        Route::post('/change-password', [AuthController::class, 'changePassword'])->middleware('throttle:5,1');
        Route::post('/email/verification-notification', [AuthController::class, 'sendVerification'])->middleware('throttle:3,1');
        Route::get('/me', [AuthController::class, 'me']);
        Route::get('/me/trips/history', [TripHistoryController::class, 'index']);
        Route::get('/trips', [TripController::class, 'index']);
        Route::get('/trips/discover', [TripController::class, 'discover']);
        Route::post('/trips', [TripController::class, 'store']);
        Route::get('/trips/{trip}', [TripController::class, 'show']);
        Route::patch('/trips/{trip}', [TripController::class, 'update']);
        Route::delete('/trips/{trip}', [TripController::class, 'destroy']);
        Route::post('/trips/{trip}/join', [TripJoinRequestController::class, 'store'])->middleware('throttle:5,1');
        Route::get('/trips/{trip}/join-requests', [TripJoinRequestController::class, 'index']);
        Route::post('/trips/{trip}/join-requests/{joinRequest}/approve', [TripJoinRequestController::class, 'approve']);
        Route::post('/trips/{trip}/join-requests/{joinRequest}/decline', [TripJoinRequestController::class, 'decline']);
        Route::delete('/trips/{trip}/join-requests/{joinRequest}', [TripJoinRequestController::class, 'cancel']);
        Route::delete('/trips/{trip}/leave', [TripController::class, 'leave']);
